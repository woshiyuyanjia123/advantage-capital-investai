    '|---|---|---|---|---|',
    '| 营业收入（亿元） | 2.18 | 3.64 | 5.40 | 与增值税申报表、出库签收单抽凭核对一致 [1] |',
    '| 综合毛利率（%） | 39.2% | 42.8% | 44.5% | 高毛利新品占比提升带动毛利结构性改善 [1] |',
    '| 扣非净利润（亿元） | 0.34 | 0.72 | 1.15 | 研发费用加计扣除合规，无跨期调节费用情形 [2] |',
    '| 经营性现金流净额（亿元） | 0.29 | 0.68 | 1.02 | 应收账款账龄 90% 在 6 个月以内，回款质量优良 [2] |',
    '',
